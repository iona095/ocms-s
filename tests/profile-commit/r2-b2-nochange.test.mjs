// R2-B2 NO_CHANGE admission. Scratch-only.
import { describe, it, beforeEach, afterEach } from 'node:test';
import path from 'node:path';
import { stringify as stringifyYaml } from 'yaml';
import { ProfileAwareCommit } from '../../profile/commit.mjs';
import { assert, makeTempHome, sandboxDshHome, buildReadyPlan, backupNames, tempNames, patchMtimeMs, readPatchBytes, minimalSources, makeProfile, bindReal, readerOpts, makeFixtureBundle, writeHomePatchText } from './helpers.mjs';
describe('R2-B2 NO_CHANGE admission', () => {
  let home; let restore; let cleanupHome;
  beforeEach(() => { restore = sandboxDshHome(); const h = makeTempHome(); home = h.home; cleanupHome = h.cleanup; });
  afterEach(() => { try { cleanupHome(); } catch {} try { restore(); } catch {} });
  it('home overlay drift refuses OVERRIDDEN with no backup or write', async () => {
    const { readManagedConfig } = await import('../../profile/config-reader.mjs');
    const { buildProfileAwarePlan } = await import('../../profile/plan-builder.mjs');
    const src = minimalSources();
    const first = await buildReadyPlan({ home });
    const desired = first.plan.desired;
    const providers = {};
    for (const [k, v] of Object.entries(desired)) providers[k] = { displayName: k, models: structuredClone(v) };
    const rows = [{ id: 'llm-pi-ai', name: '@fixture/dsh-llm-fixture', config: { providers } }];
    const dir2 = makeProfile(home, 'r2nc', { entries: rows, bundles: ['@fixture/base'] });
    makeFixtureBundle(dir2);
    const target2 = bindReal(home, 'r2nc');
    const rr2 = await readManagedConfig(readerOpts(target2));
    assert.equal(rr2.ok, true);
    const plan2 = buildProfileAwarePlan({ target: structuredClone(target2), readerResult: rr2, sources: src });
    assert.equal(plan2.status, 'NO_CHANGE');
    const evil = stringifyYaml([{ id: 'llm-pi-ai', name: '@fixture/dsh-llm-fixture', config: { providers: { opencode: { displayName: 'opencode', models: [{ id: 'home-evil' }] } } } }]);
    const { writeOverlayText: wot } = await import('./helpers.mjs');
    const overPath = wot(home, 'r2drift.yml', evil);
    plan2.target.declaredOverlays = [overPath];
    const before = readPatchBytes(dir2);
    const m0 = patchMtimeMs(dir2);
    const res = await ProfileAwareCommit({ plan: plan2, waitMs: 8000 });
    assert.equal(res.ok, false); assert.equal(res.code, 'OVERRIDDEN');
    assert.deepEqual(backupNames(dir2), []);
    assert.deepEqual(tempNames(dir2), []);
    assert.ok(readPatchBytes(dir2).equals(before));
    assert.equal(patchMtimeMs(dir2), m0);
  });
  it('production NO_CHANGE refuses LIVE_OVERLAY_UNKNOWN with no side effects', async () => {
    const prodHome = process.env.DSH_HOME;
    const { readManagedConfig } = await import('../../profile/config-reader.mjs');
    const { buildProfileAwarePlan } = await import('../../profile/plan-builder.mjs');
    const src = minimalSources();
    const first = await buildReadyPlan({ home: prodHome, profileName: 'r2ncp' });
    const desired = first.plan.desired;
    const providers = {};
    for (const [k, v] of Object.entries(desired)) providers[k] = { displayName: k, models: structuredClone(v) };
    const rows = [{ id: 'llm-pi-ai', name: '@fixture/dsh-llm-fixture', config: { providers } }];
    const dir2 = makeProfile(prodHome, 'r2ncp2', { entries: rows, bundles: ['@fixture/base'] });
    makeFixtureBundle(dir2);
    const target2 = bindReal(prodHome, 'r2ncp2');
    assert.equal(target2.classification, 'PRODUCTION');
    const rr2 = await readManagedConfig(readerOpts(target2));
    assert.equal(rr2.ok, true);
    const plan2 = buildProfileAwarePlan({ target: structuredClone(target2), readerResult: rr2, sources: src });
    assert.equal(plan2.status, 'NO_CHANGE');
    const res = await ProfileAwareCommit({ plan: plan2, waitMs: 8000 });
    assert.equal(res.ok, false); assert.equal(res.code, 'LIVE_OVERLAY_UNKNOWN');
    assert.deepEqual(backupNames(dir2), []);
  });
  it('clean NO_CHANGE still returns NO_CHANGE with no side effects', async () => {
    const { readManagedConfig } = await import('../../profile/config-reader.mjs');
    const { buildProfileAwarePlan } = await import('../../profile/plan-builder.mjs');
    const src = minimalSources();
    const first = await buildReadyPlan({ home });
    const desired = first.plan.desired;
    const providers = {};
    for (const [k, v] of Object.entries(desired)) providers[k] = { displayName: k, models: structuredClone(v) };
    const rows = [{ id: 'llm-pi-ai', name: '@fixture/dsh-llm-fixture', config: { providers } }];
    const dir2 = makeProfile(home, 'r2ncclean', { entries: rows, bundles: ['@fixture/base'] });
    makeFixtureBundle(dir2);
    const target2 = bindReal(home, 'r2ncclean');
    const rr2 = await readManagedConfig(readerOpts(target2));
    const plan2 = buildProfileAwarePlan({ target: structuredClone(target2), readerResult: rr2, sources: src });
    assert.equal(plan2.status, 'NO_CHANGE');
    const m0 = patchMtimeMs(dir2);
    const res = await ProfileAwareCommit({ plan: plan2, waitMs: 8000 });
    assert.equal(res.ok, true); assert.equal(res.status, 'NO_CHANGE');
    assert.deepEqual(backupNames(dir2), []);
    assert.equal(patchMtimeMs(dir2), m0);
  });
});
